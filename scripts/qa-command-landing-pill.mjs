import {readFileSync,existsSync} from "node:fs";
import assert from "node:assert/strict";
const root=".site/";
const html=readFileSync(root+"index.html","utf8");
const css=readFileSync(root+"assets/command-landing-pill.css","utf8");
const js=readFileSync(root+"assets/command-landing-pill.js","utf8");
const baseCss=readFileSync(root+"assets/command-center.css","utf8");
for(const file of ["assets/command-landing-pill.css","assets/command-landing-pill.js"])
  assert.ok(existsSync(root+file),"Missing compiled asset "+file);
new Function(js);
const header=html.match(/<header class="tle-landing-header"[\s\S]*?<\/header>/)?.[0];
assert.ok(header,"Missing header brand indicator");
assert.match(html,/id="tleHeaderScrollSentinel"/);
assert.match(header,/class="tle-header-surface"/);
assert.match(header,/class="tle-header-symbol"/);
assert.match(header,/class="tle-header-inner"/);
assert.match(header,/THE LAUNCH ERA/);
assert.match(header,/COMMAND CENTER/);
assert.match(header,/id="logout" class="hidden"/);
assert.ok(!/Sign in →|href="#authForm"|tle-header-action/.test(header),"Duplicate sign-in action still present in top header");
assert.equal((html.match(/id="signin"/g)||[]).length,1,"The original submit button must remain");
assert.match(html,/id="authForm"/);
assert.match(html,/assets\/command-landing-pill\.css/);
assert.match(html,/assets\/command-landing-pill\.js/);
assert.match(css,/position:fixed/);
assert.match(css,/opacity:0/);
assert.match(css,/visibility:hidden/);
assert.match(css,/body>header\.tle-landing-header\.is-floating/);
assert.match(css,/clip-path:inset\(0 0 0 0 round 999px\)/);
assert.match(css,/filter:drop-shadow/);
assert.match(css,/@media\(prefers-reduced-motion:reduce\)/);
assert.match(js,/IntersectionObserver/);
assert.ok(!/addEventListener\(['"]scroll/.test(js),"No continuous scroll listener");
assert.match(baseCss,/body:has\(#app:not\(\.hidden\)\)>header\{display:none\}/);
assert.match(css,/body:has\(#app:not\(\.hidden\)\)>header\.tle-landing-header\{display:none!important\}/);
console.log("PASS: no duplicate header CTA, scroll-only brand pill, preserved real sign-in, private UI isolation");
